export function tratadosDaUA(): readonly TratadoUA[] {
  return TRATADOS_UA;
}

export function adesaoPaisUA(pais: string, tratadoId: string): RegistroAdesao {
  const mapa = ADESAO_UA[tratadoId];
  if (!mapa || !mapa[pais]) {
    return { status: "desconhecido", ano: null };
  }
  return mapa[pais];
}

export function totalRatificacoesTratado(tratadoId: string): number {
  const mapa = ADESAO_UA[tratadoId];
  if (!mapa) return 0;
  return Object.values(mapa).filter((r) => r.status === "ratificado").length;
}
