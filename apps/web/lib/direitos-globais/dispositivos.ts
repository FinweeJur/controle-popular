/** Dispositivos de um país, na ordem em que foram conferidos. */
export function dispositivosDoPais(pais: string): readonly Dispositivo[] {
  return DISPOSITIVOS.filter((d) => d.pais === pais);
}

/** Países que já têm pelo menos um dispositivo conferido. */
export function paisesComDispositivos(): string[] {
  return [...new Set(DISPOSITIVOS.map((d) => d.pais))];
}
