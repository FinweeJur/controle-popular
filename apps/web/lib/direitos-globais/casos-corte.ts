/** Casos de um país, do mais recente para o mais antigo. */
export function casosDoPais(pais: string): readonly CasoNaCorte[] {
  return CASOS_NA_CORTE.filter((c) => c.pais === pais).sort((a, b) =>
    b.dataRemissao.localeCompare(a.dataRemissao),
  );
}

/** Países com pelo menos um caso enviado no período, em ordem alfabética. */
export function paisesComCasos(): string[] {
  return [...new Set(CASOS_NA_CORTE.map((c) => c.pais))].sort((a, b) =>
    a.localeCompare(b, "pt-BR"),
  );
}
