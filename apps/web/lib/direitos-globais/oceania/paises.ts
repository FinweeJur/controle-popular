/**
 * Busca país da Oceania por código ISO 3166-1 alpha-2.
 */
export function paisOceaniaPorCodigo(codigo: string): Pais | undefined {
  const normalizado = codigo.trim().toUpperCase();
  return PAISES_OCEANIA.find((p) => p.codigo === normalizado);
}

/**
 * Filtra países da Oceania por sub-região geográfica.
 */
export function paisesOceaniaPorSubRegiao(subRegiao: string): readonly Pais[] {
  const normalizada = subRegiao.trim().toLowerCase();
  return PAISES_OCEANIA.filter((p) => p.subRegiao.toLowerCase() === normalizada);
}
