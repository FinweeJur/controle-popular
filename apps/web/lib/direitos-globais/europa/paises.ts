/**
 * Busca país europeu por nome (insensível a maiúsculas/minúsculas).
 */
export function paisEuropeuPorNome(nome: string): PaisEuropeu | undefined {
  const normalizado = nome.trim().toLowerCase();
  return PAISES_EUROPA.find(
    (p) => p.nome.toLowerCase() === normalizado || p.id.toLowerCase() === normalizado
  );
}

/**
 * Busca país europeu por código ISO 3166-1 alpha-2.
 */
export function paisEuropeuPorCodigo(codigo: string): PaisEuropeu | undefined {
  const normalizado = codigo.trim().toUpperCase();
  return PAISES_EUROPA.find((p) => p.codigo.toUpperCase() === normalizado);
}

/**
 * Filtra países europeus pertencentes a uma determinada leva de catalogação.
 */
export function paisesEuropeusPorLeva(leva: 1): PaisEuropeu[] {
  return PAISES_EUROPA.filter((p) => p.leva === leva);
}

/**
 * Filtra países europeus por sub-região geográfica.
 */
export function paisesEuropeusPorSubRegiao(subRegiao: SubRegiaoEuropa): PaisEuropeu[] {
  return PAISES_EUROPA.filter((p) => p.subRegiao === subRegiao);
}
